REAL(KIND=JPRB)   ,INTENT(OUT),   TARGET :: PCTY0(YDGEO%YRDIM%NPROMA,0:YDGEO%YRDIMV%NFLEVG,YYTCTY0%NDIM,YDGEO%YRDIM%NGPBLKS)
REAL(KIND=JPRB)   ,INTENT(OUT),   TARGET :: PWRL9(YDGEO%YRDIM%NPROMA,YDGEO%YRDIMV%NFLEVG,YDGEO%YRDIM%NGPBLKS)
TYPE(TRAJ_TYPE)     ,INTENT(INOUT), OPTIONAL :: PTRAJEC
TYPE(TRAJ_TYPE_OOPS),INTENT(INOUT), OPTIONAL :: PTRAJEC_OOPS
!     ------------------------------------------------------------------
INTEGER(KIND=JPIM) :: JLEV, IOFF, ING
INTEGER(KIND=JPIM) :: ISETTLOFF(YDGEO%YRDIMV%NFLEVG)
INTEGER(KIND=JPIM) :: IWSETTLOFF(YDGEO%YRDIMV%NFLEVG,YDGEO%YRDIM%NGPBLKS)
REAL(KIND=JPRB)    :: ZPD_STAT
! - IRAZTS : CONTROLS INSTANTANEOUS FLUX RESET
INTEGER(KIND=JPIM) :: IRAZTS(NSTEP/YDFIELDS%YRXFU%NFRRAZ:NSTEP/YDFIELDS%YRXFU%NFRRAZ)
! - IHISTS : ARRAY CONTAINING TRAJECTORY TIME STEPS
INTEGER(KIND=JPIM), ALLOCATABLE :: IHISTS(:)
INTEGER(KIND=JPIM) :: JJ, IFRGST, IFRGST2, IPERIOD,IFRVISI,IFRVISI2,IFRPRECIP,IFRPRECIP2
LOGICAL :: LLMEAN, LLMLPP

TYPE(MF_PHYS_SURF_TYPE) :: YLMF_PHYS_SURF

TYPE(CPG_DYN_TYPE) :: YLCPG_DYN0, YLCPG_DYN9
TYPE(CPG_PHY_TYPE) :: YLCPG_PHY0, YLCPG_PHY9

TYPE(CPG_TND_TYPE) :: YLCPG_TND
TYPE(CPG_MISC_TYPE):: YLCPG_MISC
TYPE(CPG_TMP_TYPE) :: YLCPG_TMP

TYPE(CPG_OPTS_TYPE):: YLCPG_OPTS
TYPE(CPG_BNDS_TYPE):: YLCPG_BNDS
TYPE(CPG_DDH_TYPE) :: YLCPG_DDH

TYPE(CPG_SL1_TYPE)  :: YLCPG_SL1
TYPE(CPG_SL2_TYPE)  :: YLCPG_SL2

TYPE(CPG_GPAR_TYPE) :: YLCPG_GPAR
TYPE(MF_PHYS_TYPE)  :: YLMF_PHYS

LOGICAL :: LLPERSISTENT

LOGICAL :: LLUPDATE
INTEGER (KIND=JPIM) :: IBL, JKGLO

TYPE(TRAJ_PHYS_TYPE), POINTER :: ZTRAJEC_PHYS
TYPE(TRAJ_SLAG_TYPE), POINTER :: ZTRAJEC_SLAG

REAL(KIND=JPHOOK)    :: ZHOOK_HANDLE_1, ZHOOK_HANDLE_UPDATE_VIEW, ZHOOK_HANDLE_UPDATE_VIEW_1
REAL(KIND=JPHOOK)    :: ZHOOK_HANDLE_INIT, ZHOOK_HANDLE_INIT_1
REAL(KIND=JPHOOK)    :: ZHOOK_HANDLE_EXIT
REAL(KIND=JPHOOK)    :: ZHOOK_HANDLE

!     ------------------------------------------------------------------

#include "abor1.intfb.h"
#include "cpg.intfb.h"
#include "cpg_drv_reset_xfu.intfb.h"
#include "open_output_lfa.intfb.h"

!     ------------------------------------------------------------------

IF (LHOOK) CALL DR_HOOK('CPG_DRV', 0, ZHOOK_HANDLE)

ASSOCIATE(YDDIM=>YDGEO%YRDIM, YDDIMV=>YDGEO%YRDIMV, YDGEM=>YDGEO%YRGEM, &
 & YDDYN=>YDMODEL%YRML_DYN%YRDYN, YDDYNA=>YDMODEL%YRML_DYN%YRDYNA, &
 & YDRIP=>YDMODEL%YRML_GCONF%YRRIP, YDPHY=>YDMODEL%YRML_PHY_MF%YRPHY)
ASSOCIATE( NGPBLKS=>YDDIM%NGPBLKS, NFLEVG=>YDDIMV%NFLEVG, LSETFSTAT=>YDDYN%LSETFSTAT, LSETTLSVF=>YDDYN%LSETTLSVF, &
 & NCURRENT_ITER=>YDDYN%NCURRENT_ITER, NFLEVSF=>YDDYN%NFLEVSF, NGPTOTG=>YDGEM%NGPTOTG, NDGUXG=>YDDIM%NDGUXG, &
 & NDLON=>YDDIM%NDLON, NSTART=>YDRIP%NSTART, LMPHYS=>YDPHY%LMPHYS, PHYS_MWAVE=>YDPHYSMWAVE%PHYS_MWAVE, &
 & LSIMPH=>YDMODEL%YRML_PHY_MF%YRSIMPHL%LSIMPH, &
 & RSAVEDP=>YDDYN%RSAVEDP, SAVTEND=>YDMODEL%YRML_PHY_G%YRSLPHY%SAVTEND, YYTTND=>YDDYNA%YYTTND)

IF (LMUSCLFA) CALL OPEN_OUTPUT_LFA(YDMODEL%YRML_PHY_MF%YRPHY2)

!     ------------------------------------------------------------------

CALL YLCPG_OPTS%INIT (YDGEO, YDMODEL, YDFIELDS, CDCONF, LD_DFISTEP)

CALL CPG_DRV_RESET_XFU (YLCPG_OPTS, YDFIELDS, YDMODEL)

!     ------------------------------------------------------------------
!*       3.    READ BUFFERS, COMPUTE AUXILIARY QUANTITIES.
!              -------------------------------------------


IF (LHOOK) CALL DR_HOOK('CPG_DRV:INIT', 0, ZHOOK_HANDLE_INIT)

LLPERSISTENT = .FALSE.

CALL YLCPG_BNDS%INIT (YDGEO, YDMODEL, YDFIELDS)
CALL YLMF_PHYS_SURF%INIT (YDFIELDS%SURFVARS)


IF (LHOOK) CALL DR_HOOK('CPG_DRV:INIT', 0, ZHOOK_HANDLE_INIT_1)

CALL YLCPG_DYN0%INIT (0_JPIM, YDFIELDS%REGISTRY, NLEV=NFLEVG, PHIF=PHIF0, PRCP=PRCP0, PREF=PRE0F, PCTY=PCTY0, &
& PERSISTENT=LLPERSISTENT, YDDYNA=YDMODEL%YRML_DYN%YRDYNA)

CALL YLCPG_PHY0%INIT (0_JPIM, YDFIELDS%REGISTRY, NLEV=NFLEVG, LDMF_PHYS=LMPHYS.OR.LSIMPH, PERSISTENT=LLPERSISTENT&
& )

CALL YLCPG_SL1%INIT (YDFIELDS%REGISTRY, NLEV=NFLEVG, YDTPTRSLB1=YDMODEL%YRML_DYN%YRPTRSLB1, YGFL=YDFIELDS%YRGFL%YGFL, &
& YDMODEL=YDMODEL, PERSISTENT=LLPERSISTENT)

!IF (.NOT. YDDYNA%LTWOTL) THEN
  CALL YLCPG_DYN9%INIT (9_JPIM, YDFIELDS%REGISTRY, NLEV=NFLEVG, PWRL=PWRL9, PERSISTENT=LLPERSISTENT, YDDYNA=YDMODEL%YRML_DYN%YRDYNA)
  CALL YLCPG_PHY9%INIT (9_JPIM, YDFIELDS%REGISTRY, NLEV=NFLEVG, LDMF_PHYS=LMPHYS.OR.LSIMPH, PERSISTENT=LLPERSISTENT&
  & )
!ENDIF

CALL YLCPG_TMP%INIT (YDFIELDS%REGISTRY, NLEV=NFLEVG, PERSISTENT=LLPERSISTENT, YDDYNA=YDMODEL%YRML_DYN%YRDYNA)

CALL YLCPG_TND%INIT (YDFIELDS%REGISTRY, NLEV=NFLEVG, YDTTND=YYTTND, PERSISTENT=LLPERSISTENT)

CALL YLCPG_MISC%INIT (YDFIELDS%REGISTRY, YDCPG_OPTS=YLCPG_OPTS, PERSISTENT=LLPERSISTENT)

CALL YLMF_PHYS%OUT%INIT (YDFIELDS%REGISTRY, YDCPG_OPTS=YLCPG_OPTS, PERSISTENT=LLPERSISTENT)

CALL YLMF_PHYS%OPT%INIT (YDFIELDS%REGISTRY, YDCPG_OPTS=YLCPG_OPTS, LDMF_PHYS=LMPHYS.OR.LSIMPH, PGDEOSI=PGDEOSI,      &
& PGUEOSI=PGUEOSI, PGMU0=PGMU0, PGMU0_MIN=PGMU0_MIN, PGMU0_MAX=PGMU0_MAX, PGDEOTI=PGDEOTI, PGDEOTI2=PGDEOTI2,        &
& PGUEOTI=PGUEOTI, PGUEOTI2=PGUEOTI2, PGEOLT=PGEOLT, PGEOXT=PGEOXT, PGRPROX=PGRPROX, PGMIXP=PGMIXP, PGFLUXC=PGFLUXC, &
& PGRSURF=PGRSURF, PERSISTENT=LLPERSISTENT)

CALL YLMF_PHYS%FOR%INIT (YDFIELDS%REGISTRY, YDCPG_OPTS=YLCPG_OPTS, LDMF_PHYS=LMPHYS.OR.LSIMPH, PU=PFORCEU, &
& PV=PFORCEV, PT=PFORCET, PQ=PFORCEQ, PERSISTENT=LLPERSISTENT)

CALL YLMF_PHYS%GRA%INIT (YDFIELDS%REGISTRY, YDCPG_OPTS=YLCPG_OPTS, LDMF_PHYS=LMPHYS.OR.LSIMPH, PG=PGRADPHY, &
& PERSISTENT=LLPERSISTENT)

CALL YLMF_PHYS%RAD%INIT (YDFIELDS%REGISTRY, YDCPG_OPTS=YLCPG_OPTS, LDMF_PHYS=LMPHYS.OR.LSIMPH, PEMTD=PEMTD, &
& PEMTU=PEMTU, PTRSW=PTRSW, PRMOON=PRMOON, PERSISTENT=LLPERSISTENT)

IF (LHOOK) CALL DR_HOOK('CPG_DRV:INIT', 1, ZHOOK_HANDLE_INIT_1)

CALL YLCPG_GPAR%INIT (YDFIELDS%REGISTRY, YLCPG_OPTS, YDMODEL%YRML_PHY_MF%YRPARAR, PERSISTENT=LLPERSISTENT&
& )
CALL YLCPG_SL2%INIT (YDFIELDS%REGISTRY, NLEV=NFLEVG, YDTPTRSLB2=YDMODEL%YRML_DYN%YRPTRSLB2, PB2=PB2, &
& PERSISTENT=LLPERSISTENT)
CALL YLCPG_DDH%INIT (YDFIELDS%REGISTRY, NLEV=NFLEVG, YDMODEL=YDMODEL, YDDDH=YDDDH, PERSISTENT=LLPERSISTENT&
& )

IF (YDMODEL%YRML_PHY_MF%YRPHY%LMPHYS .OR. LSIMPH) THEN

  ! From aplpar.F90
  IF (.NOT. YDMODEL%YRML_PHY_MF%YRARPHY%LMPA) THEN
    YDMODEL%YRML_PHY_MF%YRPHY2%TSPHY = MAX (YLCPG_OPTS%ZDTPHY,1.0_JPRB)
  ENDIF

  ! From acnebr.F90
  IF (YDMODEL%YRML_PHY_MF%YRPHY%LNEBR) THEN
    IF(YDMODEL%YRML_PHY_MF%YRPHY%LRAY) THEN
      IF(YDMODEL%YRML_PHY_MF%YRPHY%LRNUMX) THEN
        YDMODEL%YRML_PHY_RAD%YRERAD%NOVLP=1
      ELSE
        YDMODEL%YRML_PHY_RAD%YRERAD%NOVLP=3
      ENDIF
    ENDIF
    IF(YDMODEL%YRML_PHY_MF%YRPHY%LRAYFM) THEN
      IF(YDMODEL%YRML_PHY_RAD%YRERAD%NOVLP == 1.OR.YDMODEL%YRML_PHY_RAD%YRERAD%NOVLP == 2) THEN
        YDMODEL%YRML_PHY_MF%YRPHY%LRNUMX=.TRUE.
      ELSE
        YDMODEL%YRML_PHY_MF%YRPHY%LRNUMX=.FALSE.
      ENDIF
    ENDIF
    IF(YDMODEL%YRML_PHY_MF%YRPHY%LRAYFM15) THEN
      CALL ABOR1('RADIATION SCHEME FROM CYCLE 15 NO LONGER AVAILABLE')
    ENDIF
  ENDIF
ENDIF

IF (LHOOK) CALL DR_HOOK('CPG_DRV:INIT', 1, ZHOOK_HANDLE_INIT)

CALL GSTATS(1025, 0)

!$OMP PARALLEL PRIVATE (LLUPDATE, JKGLO, IBL, ZTRAJEC_PHYS, ZTRAJEC_SLAG) &
!$OMP & PRIVATE (ZHOOK_HANDLE_UPDATE_VIEW, ZHOOK_HANDLE_1, ZHOOK_HANDLE_UPDATE_VIEW_1) &
!$OMP & FIRSTPRIVATE (YDVARS)

IF (LHOOK) CALL DR_HOOK('CPG_DRV:YDVARS%CLONE_ARRAYS', 0, ZHOOK_HANDLE_1)
CALL YDVARS%CLONE_ARRAYS
IF (LHOOK) CALL DR_HOOK('CPG_DRV:YDVARS%CLONE_ARRAYS', 1, ZHOOK_HANDLE_1)

LLUPDATE = .TRUE.

!$OMP DO SCHEDULE(DYNAMIC,1) FIRSTPRIVATE (YDDDH) LASTPRIVATE (YDDDH) &
!$OMP & FIRSTPRIVATE (YLMF_PHYS_SURF, YLCPG_DYN0, YLCPG_DYN9, YLCPG_PHY0, YLCPG_PHY9, YLCPG_TND, &
!$OMP &               YLCPG_MISC, YLCPG_TMP, YLCPG_DDH, YLCPG_SL1, YLCPG_SL2, YLCPG_GPAR, YLMF_PHYS, YLCPG_BNDS, &
!$OMP &               PPGTERM)

DO JKGLO = 1, KGPCOMP, YDGEO%YRDIM%NPROMA

  IBL=(JKGLO-1)/YDGEO%YRDIM%NPROMA+1
  
  IWSETTLOFF(:,IBL) = 0

  IF (LHOOK) CALL DR_HOOK('CPG_DRV:UPDATE_VIEW', 0, ZHOOK_HANDLE_UPDATE_VIEW)

  IF (LHOOK) CALL DR_HOOK('CPG_DRV:UPDATE_VIEW:YDVARS', 0, ZHOOK_HANDLE_UPDATE_VIEW_1)
  CALL YDVARS%UPDATE_VIEW (BLOCK_INDEX=IBL)
  IF (LHOOK) CALL DR_HOOK('CPG_DRV:UPDATE_VIEW:YDVARS', 1, ZHOOK_HANDLE_UPDATE_VIEW_1)
  IF (LHOOK) CALL DR_HOOK('CPG_DRV:UPDATE_VIEW:YLMF_PHYS_SURF', 0, ZHOOK_HANDLE_UPDATE_VIEW_1)
  CALL YLMF_PHYS_SURF%UPDATE_VIEW (BLOCK_INDEX=IBL)
  IF (LHOOK) CALL DR_HOOK('CPG_DRV:UPDATE_VIEW:YLMF_PHYS_SURF', 1, ZHOOK_HANDLE_UPDATE_VIEW_1)

  IF (LHOOK) CALL DR_HOOK('CPG_DRV:UPDATE_VIEW:OTHER', 0, ZHOOK_HANDLE_UPDATE_VIEW_1)

  CALL YLCPG_DYN0%UPDATE_VIEW (BLOCK_INDEX=IBL)
  CALL YLCPG_DYN9%UPDATE_VIEW (BLOCK_INDEX=IBL)
  CALL YLMF_PHYS%OUT%UPDATE_VIEW (BLOCK_INDEX=IBL)
  CALL YLMF_PHYS%OPT%UPDATE_VIEW (BLOCK_INDEX=IBL)
  CALL YLMF_PHYS%FOR%UPDATE_VIEW (BLOCK_INDEX=IBL)
  CALL YLMF_PHYS%GRA%UPDATE_VIEW (BLOCK_INDEX=IBL)
  CALL YLMF_PHYS%RAD%UPDATE_VIEW (BLOCK_INDEX=IBL)

  IF (LHOOK) CALL DR_HOOK('CPG_DRV:UPDATE_VIEW:OTHER', 1, ZHOOK_HANDLE_UPDATE_VIEW_1)

  IF (LLUPDATE) THEN
    IF (LHOOK) CALL DR_HOOK('CPG_DRV:UPDATE_VIEW:OTHER.ONCE', 0, ZHOOK_HANDLE_UPDATE_VIEW_1)

    CALL YLCPG_PHY0%UPDATE_VIEW (BLOCK_INDEX=IBL)
    CALL YLCPG_PHY9%UPDATE_VIEW (BLOCK_INDEX=IBL)
    CALL YLCPG_TND%UPDATE_VIEW (BLOCK_INDEX=IBL)
    CALL YLCPG_TMP%UPDATE_VIEW (BLOCK_INDEX=IBL)
    CALL YLCPG_MISC%UPDATE_VIEW (BLOCK_INDEX=IBL)
    CALL YLCPG_SL1%UPDATE_VIEW (BLOCK_INDEX=IBL)

    CALL YLCPG_GPAR%UPDATE_VIEW (IBL)
    CALL YLCPG_DDH%UPDATE_VIEW (IBL)

    LLUPDATE = .FALSE.
    IF (LHOOK) CALL DR_HOOK('CPG_DRV:UPDATE_VIEW:OTHER.ONCE', 1, ZHOOK_HANDLE_UPDATE_VIEW_1)
  ENDIF

  CALL YLCPG_SL2%UPDATE_VIEW (IBL)

  CALL YLCPG_BNDS%UPDATE (IBL)
  
  IF (LHOOK) CALL DR_HOOK('CPG_DRV:UPDATE_VIEW', 1, ZHOOK_HANDLE_UPDATE_VIEW)

  CALL PPGTERM%UPDATE_VIEW (IBL)

  IF(PRESENT(PTRAJEC))THEN
    CALL SC2PRG(IBL, PTRAJEC%PHYS, ZTRAJEC_PHYS)
    CALL SC2PRG(IBL, PTRAJEC%SLAG, ZTRAJEC_SLAG)
  ELSE
    CALL SC2PRG(IBL, PTRAJEC_OOPS%PHYS, ZTRAJEC_PHYS)
    CALL SC2PRG(IBL, PTRAJEC_OOPS%SLAG, ZTRAJEC_SLAG)
  ENDIF

  CALL CPG(YDGEO, YLCPG_BNDS, YLCPG_OPTS, YLCPG_TMP, YLCPG_TND, YLCPG_SL1, YLCPG_SL2,&
  & YLCPG_MISC, YLCPG_GPAR, YLCPG_PHY0, YLCPG_PHY9, YLMF_PHYS, YLCPG_DDH, YLCPG_DYN0, YLCPG_DYN9, &
  & YLMF_PHYS_SURF, YDVARS, YDMODEL, YDFIELDS, YDSL, PGFLSLP(:, :, :, IBL), SAVTEND(:, :, :, IBL), PGMVTNDHD_DDH(:, :, :, IBL), &
  & PGFLTNDHD_DDH(:, :, :, IBL), PGPSDT2D(:, :, IBL), PSD_PF(:, :, :, IBL), PPGTERM, PGMV(:, :, :, IBL), PGMVS(:, :, IBL),  &
  & PGFL(:, :, :, IBL), PGFLPC(:, :, :, IBL), PGFLPT(:, :, :, IBL), PSD_XA(:, :, :, IBL), PGMVTNDSI_DDH(:, :, :, IBL), PHYS_MWAVE(:,:,:,IBL), &
  & IWSETTLOFF(:, IBL), PB1, PGMVT1(:, :, :, IBL), PGMVT1S(:, :, IBL), PGFLT1(:, :, :, IBL), PEXTRA(:, :, :, IBL), &
  & PGMVTNDSL_DDH(:, :, :, IBL), PGFLTNDSL_DDH(:, :, :, IBL), ZTRAJEC_PHYS, ZTRAJEC_SLAG, YDDDH, CDPART='XXX', &
  & PSAVEDP=RSAVEDP(:,:,:,IBL)                )

ENDDO

!$OMP END DO

IF (LHOOK) CALL DR_HOOK('CPG_DRV:YDVARS%RESET_ARRAYS', 0, ZHOOK_HANDLE_1)
CALL YDVARS%RESET_ARRAYS ()
IF (LHOOK) CALL DR_HOOK('CPG_DRV:YDVARS%RESET_ARRAYS', 1, ZHOOK_HANDLE_1)

!$OMP END PARALLEL 

CALL GSTATS(1025, 1)

IF (LHOOK) CALL DR_HOOK('CPG_DRV:EXIT', 0, ZHOOK_HANDLE_EXIT)

CALL YLCPG_DYN0%FINAL
CALL YLCPG_DYN9%FINAL
CALL YLCPG_PHY0%FINAL
CALL YLCPG_PHY9%FINAL
CALL YLMF_PHYS_SURF%FINAL
CALL YLMF_PHYS%FINAL
CALL YLCPG_TND%FINAL
CALL YLCPG_MISC%FINAL
CALL YLCPG_TMP%FINAL
CALL YLCPG_DDH%FINAL
CALL YLCPG_SL1%FINAL
CALL YLCPG_SL2%FINAL
CALL YLCPG_GPAR%FINAL
CALL PPGTERM%FINAL

IF (LHOOK) CALL DR_HOOK('CPG_DRV:EXIT', 1, ZHOOK_HANDLE_EXIT)

IF (LSETTLSVF.AND.NSTEP>NSTART.AND.LSETFSTAT) THEN
  ISETTLOFF=0
  DO JLEV=1,NFLEVSF
    DO IBL=1,NGPBLKS
      ISETTLOFF(JLEV)=ISETTLOFF(JLEV)+IWSETTLOFF(JLEV,IBL)
    ENDDO
  ENDDO

  IF (NPROC>1) THEN
    CALL MPL_ALLREDUCE( ISETTLOFF, 'SUM', LDREPROD=.FALSE., CDSTRING='CPG_DRV:')
  ENDIF

  IF (MYPROC == 1) THEN
    DO JLEV=1,NFLEVSF
      WRITE(NULOUT,*) '% of pts extrapolation is off at lev:',JLEV,'is:',100.*ISETTLOFF(JLEV)/NGPTOTG
    ENDDO
  ENDIF
ENDIF

! global characteristics for LMIXETTLS scheme
! temporarily ISETTLOFF is used
IF (YDDYNA%LMIXETTLS.AND.NSTEP>NSTART) THEN
  IF (LRPLANE) THEN

    ING = NDGUXG * NDLON
    ! accumulate characteristics for all NPROMA packets
    ISETTLOFF=0
    DO JLEV=1,NFLEVG
      DO IBL=1,NGPBLKS
        ISETTLOFF(JLEV)=ISETTLOFF(JLEV)+IWSETTLOFF(JLEV,IBL)
      ENDDO
    ENDDO

    ! global sum over processors
    IF (NPROC>1) THEN
      CALL MPL_ALLREDUCE( ISETTLOFF, 'SUM', LDREPROD=.FALSE., CDSTRING='CPG_DRV:')
    ENDIF

    ! compute on all processors
    IF (NCURRENT_ITER == 0) THEN
      DO JLEV=1,NFLEVG
        IOFF    = JLEV
        ZPD_STAT= REAL(ISETTLOFF(IOFF),JPRB)/REAL(ING,JPRB) * 100.0_JPRB
      ENDDO
    ENDIF

    ! write only on proc 1
    IF (MYPROC == 1) THEN
      DO JLEV=1,NFLEVG
        IOFF    = JLEV
        ZPD_STAT= REAL(ISETTLOFF(IOFF),JPRB)/REAL(ING,JPRB) * 100.0_JPRB
        IF (YDDYNA%LMIXETTLS_PRINT.AND.(NCURRENT_ITER==0)) THEN
          WRITE(NULOUT,'(A,2(I5,";"),F15.8)') 'CPG_DRV STATISTICS: ', NSTEP, JLEV, ZPD_STAT
        ENDIF
      ENDDO
    ENDIF

  ELSE
    CALL ABOR1('CPG_DRV: GLOBAL GEOMETRY NOT YET CODED FOR MIXED TTL SCHEME.')
  ENDIF
ENDIF

IF (LMUSCLFA) CALL LFAFER(NMUSCLFA)

!     ------------------------------------------------------------------
END ASSOCIATE
END ASSOCIATE
IF (LHOOK) CALL DR_HOOK('CPG_DRV', 1, ZHOOK_HANDLE)

END SUBROUTINE CPG_DRV

