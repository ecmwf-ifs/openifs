!**** *CPG_DRV* - Grid point calculations driver routine.

!     Purpose.
!     --------
!           Do the parallel loop calling CPG, the grid point calculations.

!**   Interface.
!     ----------
!        *CALL* *CPG_DRV(...)*

!        Explicit arguments :
!        --------------------

!     INPUT:
!     ------
!        CDCONF       : configuration of work
!        LD_DFISTEP   : T if work - dfi
