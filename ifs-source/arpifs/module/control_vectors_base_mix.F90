SUBROUTINE ASSIGN_AR_CV(YDCV,PVEC)
CLASS(CONTROL_VECTOR), INTENT(INOUT) :: YDCV
REAL(KIND=JPRB), INTENT(IN) :: PVEC(:)
INTEGER(KIND=JPIM) :: ILEN,IOFF,JF,II,JJ,JL,IL,IBGN,IEND,IGPTOTG,JSCALE,JA,JB
INTEGER(KIND=JPIM), ALLOCATABLE :: IGRB(:)
TYPE(SPECTRAL_FIELD) :: YLSP

REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
IF (LHOOK) CALL DR_HOOK('CONTROL_VECTORS_OPER_MOD:ASSIGN_AR_CV',0,ZHOOK_HANDLE)
CALL CHECK_CV(YDCV)

IF (SIZE(PVEC) == YDCV%NSIZEL) THEN
  YDCV%DATA = PVEC
ELSEIF (SIZE(PVEC) == YDCV%NSIZEG) THEN
  IF (YDCV%LINITCV) THEN
    IF (.NOT.YDCV%INITCV%LWAVELETJB) THEN
      CALL ALLOCATE_SPEC(YLSP,YDCV%STRUCT%NFLEVL,YDCV%STRUCT%NFLEVG, &
       & YDCV%STRUCT%NUMP,YDCV%STRUCT%MYMS,YDCV%NSMAX,YDCV%NMSMAX, &
       & YDCV%STRUCT%NALLMS,YDCV%STRUCT%NPTRMS,YDCV%STRUCT%NUMLL, &
       & YDCV%STRUCT%NPTRLL,YDCV%STRUCT%NPSURF,YDCV%NS3D,YDCV%NS2D,&
       & YDCV%STRUCT%NGRB)
      ILEN=YLSP%NSPSIZEG
      YLSP=PVEC(1:ILEN)
      YDCV%INITCV%DATA(:)=YLSP
      IOFF=ILEN
      CALL DEALLOCATE_SPEC(YLSP)
    ELSE
      IGPTOTG=0
      DO JSCALE=1,YDCV%NSCALES
        DO JA=1,YDCV%STRUCT%N_REGIONS_NS
          DO JB=1,YDCV%STRUCT%N_REGIONS(JA)
            IF (JA==YDCV%STRUCT%MY_REGION_NS .AND. JB==YDCV%STRUCT%MY_REGION_EW) THEN
              IBGN=YDCV%INITCV%IBGN_SCALE(JSCALE)
              ILEN=YDCV%STRUCT%NPROMA*(YDCV%STRUCT%NFLEVG*YDCV%NS3D+YDCV%NS2D) &
                       & *YDCV%STRUCT%NBLOCKSL(JSCALE+YDCV%STRUCT%NSCALES-YDCV%NSCALES)
              IEND=IBGN+ILEN-1
              YDCV%INITCV%DATA(IBGN:IEND) = PVEC(IGPTOTG+1:IGPTOTG+ILEN)
            ENDIF
            IGPTOTG=IGPTOTG+YDCV%STRUCT%NGPTOTL(JSCALE+YDCV%STRUCT%NSCALES-YDCV%NSCALES,JA,JB)
          ENDDO
        ENDDO
      ENDDO
      IF (IGPTOTG /= SUM(YDCV%STRUCT%NGPTOTG(1+YDCV%STRUCT%NSCALES-YDCV%NSCALES:))) &
        & CALL ABOR1 ('assign_ar_cv: indexing problem')
      IOFF = IGPTOTG
    ENDIF
  ENDIF

  IF (YDCV%LENSCV) THEN
     ALLOCATE(IGRB(2*YDCV%NENS))
     DO II=1,2*YDCV%NENS
        IGRB(II)=1000+II
     ENDDO
     CALL ALLOCATE_SPEC(YLSP,YDCV%STRUCT_ENS%NFLEVL,YDCV%STRUCT_ENS%NFLEVG, &
          & YDCV%STRUCT_ENS%NUMP,YDCV%STRUCT_ENS%MYMS,YDCV%NSMAX_ENS,YDCV%NMSMAX_ENS, &
          & YDCV%STRUCT_ENS%NALLMS,YDCV%STRUCT_ENS%NPTRMS,YDCV%STRUCT_ENS%NUMLL, &
          & YDCV%STRUCT_ENS%NPTRLL,YDCV%STRUCT_ENS%NPSURF,YDCV%NENS,YDCV%NENS,IGRB)
     ILEN=YLSP%NSPSIZEG
     YLSP=PVEC(1:ILEN)
     YDCV%ENSCV%DATA(:)=YLSP
     IOFF=ILEN
     CALL DEALLOCATE_SPEC(YLSP)
     DEALLOCATE(IGRB)
  ENDIF

  IF (YDCV%NMODERR>0) THEN
    CALL ALLOCATE_SPEC(YLSP,YDCV%STRUCT%NFLEVL,YDCV%STRUCT%NFLEVG, &
      & YDCV%STRUCT%NUMP,YDCV%STRUCT%MYMS,YDCV%NSERR,YDCV%NSERR, &
      & YDCV%STRUCT%NALLMS,YDCV%STRUCT%NPTRMS,YDCV%STRUCT%NUMLL, &
      & YDCV%STRUCT%NPTRLL,YDCV%STRUCT%NPSURF,YDCV%NVE3D,YDCV%NVE2D, &
      & YDCV%STRUCT%NGRBE)
    ILEN=YLSP%NSPSIZEG
    IL=YLSP%NSPSIZEL
    DO JJ=1,YDCV%NMODERR
      II=(JJ-1)*IL
      YLSP=PVEC(IOFF+1:IOFF+ILEN)
      YDCV%MODERR(II+1:II+IL)=YLSP
      IOFF=IOFF+ILEN
    ENDDO
    CALL DEALLOCATE_SPEC(YLSP)
  ENDIF
  IF (YDCV%LTOVSCV) THEN
    JL=0
    DO JF=1,YDCV%STRUCT%NVATOVV
      DO JJ=1,YDCV%STRUCT%NLENTOVSCV
        JL=JL+1
        YDCV%TOVSCV(JL)=PVEC(IOFF+YDCV%STRUCT%MYTOVOFF+JJ)
      ENDDO
      IOFF=IOFF+YDCV%STRUCT%NLENTOVSCVG
    ENDDO
  ENDIF

  IF (YDCV%LAM1D) THEN
    JJ=0
    DO JF=1,YDCV%NS1D
      DO JL=1,YDCV%STRUCT%NFLEVL
        IL=YDCV%STRUCT%MYLEVS(JL)
        JJ=JJ+1
        YDCV%LAMCV(JJ)=PVEC(IOFF+IL)
      ENDDO
      IOFF=IOFF+YDCV%STRUCT%NFLEVG
    ENDDO
  ENDIF
  IF (YDCV%NPARA>0) THEN
    DO JF=1,YDCV%NPARA
      YDCV%PARAMS(JF)=PVEC(IOFF+JF)
    ENDDO
    IOFF=IOFF+YDCV%NPARA
  ENDIF
  IF (YDCV%NPECV>0) THEN
    DO JF=1,YDCV%NPECV
      YDCV%PECV(JF)=PVEC(IOFF+JF)
    ENDDO
    IOFF=IOFF+YDCV%NPECV
  ENDIF
ELSE
  CALL ABOR1('Error: cannot assign array to control vector')
ENDIF

IF (LHOOK) CALL DR_HOOK('CONTROL_VECTORS_OPER_MOD:ASSIGN_AR_CV',1,ZHOOK_HANDLE)
END SUBROUTINE ASSIGN_AR_CV

