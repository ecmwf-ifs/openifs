SUBROUTINE ASSIGN_CV_AR(PVEC,YDCV)
REAL(KIND=JPRB), INTENT(OUT) :: PVEC(:)
CLASS(CONTROL_VECTOR), INTENT(IN) :: YDCV

REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
IF (LHOOK) CALL DR_HOOK('CONTROL_VECTORS_OPER_MOD:ASSIGN_CV_AR',0,ZHOOK_HANDLE)
CALL CHECK_CV(YDCV)
IF (SIZE(PVEC) == YDCV%NSIZEL) THEN
  PVEC = YDCV%DATA
ELSEIF (SIZE(PVEC) == YDCV%NSIZEG) THEN
!  This case has to come after the preceeding one so that it isn't
!  executed if running on one processor.
  CALL ABOR1('Assign vector to global array would be very expensive')
ELSE
  CALL ABOR1('Error: cannot assign control vector to array')
ENDIF

IF (LHOOK) CALL DR_HOOK('CONTROL_VECTORS_OPER_MOD:ASSIGN_CV_AR',1,ZHOOK_HANDLE)
END SUBROUTINE ASSIGN_CV_AR

