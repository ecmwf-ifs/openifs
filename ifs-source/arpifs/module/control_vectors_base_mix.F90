SUBROUTINE INVERSE_CV_CV(YDIN,YDOUT)
TYPE(CONTROL_VECTOR), INTENT(IN)    :: YDIN
CLASS(CONTROL_VECTOR), INTENT(INOUT) :: YDOUT

! divide_cv fails on zero, inverse sets output to zero.
REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
IF (LHOOK) CALL DR_HOOK('CONTROL_VECTORS_OPER_MOD:INVERSE_CV_CV',0,ZHOOK_HANDLE)
CALL CHECK_CV_CV(YDIN,YDOUT)

WHERE (YDIN%DATA == 0.0_JPRB)
  YDOUT%DATA = 0.0_JPRB
ELSEWHERE
  YDOUT%DATA = 1.0_JPRB/YDIN%DATA
ENDWHERE

IF (LHOOK) CALL DR_HOOK('CONTROL_VECTORS_OPER_MOD:INVERSE_CV_CV',1,ZHOOK_HANDLE)
END SUBROUTINE INVERSE_CV_CV

