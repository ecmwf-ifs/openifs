SUBROUTINE ASSIGN_CV_CV(YDCV1,YDCV2)
CLASS(CONTROL_VECTOR), INTENT(INOUT) :: YDCV1
TYPE(CONTROL_VECTOR), INTENT(IN)    :: YDCV2
TYPE(SPECTRAL_FIELD) :: YLSP1, YLSP2
LOGICAL :: LL_SAME_INIT, LL_SAME_ENS, LL_SAME_MODERR
INTEGER(KIND=JPIM) :: ILEN,I1,I2,IL1,IL2,JJ,J,II
INTEGER(KIND=JPIM), ALLOCATABLE :: IGRB(:)
REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
IF (LHOOK) CALL DR_HOOK('CONTROL_VECTORS_OPER_MOD:ASSIGN_CV_CV',0,ZHOOK_HANDLE)
CALL CHECK_CV(YDCV1)
CALL CHECK_CV(YDCV2)
IF (NEQUIV_CV(YDCV1,YDCV2)) THEN
  CALL ABOR1('Control vectors are incompatible')
ENDIF

LL_SAME_INIT = .TRUE.
IF (YDCV1%LINITCV) THEN
  IF (YDCV1%INITCV%LWAVELETJB) THEN
    LL_SAME_INIT = YDCV1%NSCALES==YDCV2%NSCALES.AND.(YDCV1%NSERR==YDCV2%NSERR)
  ELSE
    LL_SAME_INIT = YDCV1%NSMAX==YDCV2%NSMAX .AND. (YDCV1%NSERR==YDCV2%NSERR)
  ENDIF
ENDIF

IF (YDCV1%LENSCV) THEN
   LL_SAME_ENS = (YDCV1%NENS==YDCV2%NENS .AND. YDCV1%NSMAX_ENS==YDCV2%NSMAX_ENS) ! detects change of resolution
ENDIF

IF (YDCV1%LELAM) THEN
  LL_SAME_INIT = LL_SAME_INIT .AND. (YDCV1%NMSMAX==YDCV2%NMSMAX)
ENDIF

IF (YDCV1%NMODERR>0) THEN
  LL_SAME_MODERR = (YDCV1%NSERR==YDCV2%NSERR)
ELSE
  LL_SAME_MODERR = .TRUE.
ENDIF

IF (LL_SAME_INIT .AND. LL_SAME_MODERR .AND. LL_SAME_ENS) THEN
  CALL GSTATS(1460,0)
!$OMP PARALLEL DO SCHEDULE(STATIC) PRIVATE(J)
  DO J=1,SIZE(YDCV1%DATA)
    YDCV1%DATA(J) = YDCV2%DATA(J)
  ENDDO
!$OMP END PARALLEL DO
  CALL GSTATS(1460,1)
ELSE
  IF (YDCV1%LINITCV) THEN
    IF (LL_SAME_INIT) THEN
      YDCV1%INITCV%DATA(:) = YDCV2%INITCV%DATA(:)
    ELSEIF (YDCV1%INITCV%LWAVELETJB) THEN
      IF (YDCV1%LELAM) CALL  ABOR1('LELAM-wavelets not implemented here.')
!---- NB: The finest scale of the lower-resolution control vector (ydcv2 or ydcv1)
!     has a different grid than the corresponding scale of higher-resolution
!     control vector (ydcv1 or ydcv2). Ideally,
!     we should use the spherical transform to re-grid this scale. But,
!     for now we just zero it in ydcv1.

      ! Input control vector YDCV2 at lower resolution, zero finest input scale
      IF (YDCV1%NSCALES > YDCV2%NSCALES) THEN
        ILEN=YDCV1%INITCV%IBGN_SCALE(YDCV1%NSCALES-YDCV2%NSCALES+2)-1
        YDCV1%INITCV%DATA(1:ILEN) = 0.0_JPRB
        IF (  SIZE(YDCV1%INITCV%DATA(ILEN+1:)) &
          & /=SIZE(YDCV2%INITCV%DATA(YDCV2%INITCV%IBGN_SCALE(2):))) THEN
          WRITE(0,*)'size mismatch: ',SIZE(YDCV1%INITCV%DATA(ILEN+1:)), &
                   &                  SIZE(YDCV2%INITCV%DATA(YDCV2%INITCV%IBGN_SCALE(2):))
          WRITE(0,*)'ydcv1%initcv%ibgn_scale=',YDCV1%INITCV%IBGN_SCALE
          WRITE(0,*)'ydcv2%initcv%ibgn_scale=',YDCV2%INITCV%IBGN_SCALE
          CALL ABOR1 ('size mismatch')
        ENDIF
        YDCV1%INITCV%DATA(ILEN+1:) = YDCV2%INITCV%DATA(YDCV2%INITCV%IBGN_SCALE(2):)
      ! Input control vector YDCV2 at higher resolution, zero input scales up
      ! to and including the finest scale of YDC1
      ELSEIF (YDCV1%NSCALES < YDCV2%NSCALES) THEN
        ILEN=YDCV2%INITCV%IBGN_SCALE(YDCV2%NSCALES-YDCV1%NSCALES+2)-1
        YDCV1%INITCV%DATA(1:YDCV1%INITCV%IBGN_SCALE(2)-1) = 0.0_JPRB
        IF (  SIZE(YDCV2%INITCV%DATA(ILEN+1:)) &
          & /=SIZE(YDCV1%INITCV%DATA(YDCV1%INITCV%IBGN_SCALE(2):))) THEN
          WRITE(0,*)'size mismatch: ',SIZE(YDCV2%INITCV%DATA(ILEN+1:)), &
                   &                  SIZE(YDCV1%INITCV%DATA(YDCV1%INITCV%IBGN_SCALE(2):))
          WRITE(0,*)'ydcv1%initcv%ibgn_scale=',YDCV1%INITCV%IBGN_SCALE
          WRITE(0,*)'ydcv2%initcv%ibgn_scale=',YDCV2%INITCV%IBGN_SCALE
          CALL ABOR1 ('size mismatch')
        ENDIF
        YDCV1%INITCV%DATA(YDCV1%INITCV%IBGN_SCALE(2):) = YDCV2%INITCV%DATA(ILEN+1:)
      ELSE
        ! Input control vector YDCV2 of same resolution
        YDCV1%INITCV%DATA(:) = YDCV2%INITCV%DATA(:)
      ENDIF
    ELSE
      CALL ALLOCATE_SPEC(YLSP1,YDCV1%STRUCT%NFLEVL,YDCV1%STRUCT%NFLEVG, &
        & YDCV1%STRUCT%NUMP,YDCV1%STRUCT%MYMS,YDCV1%NSMAX,YDCV1%NMSMAX, &
        & YDCV1%STRUCT%NALLMS,YDCV1%STRUCT%NPTRMS,YDCV1%STRUCT%NUMLL, &
        & YDCV1%STRUCT%NPTRLL, YDCV1%STRUCT%NPSURF,YDCV1%NS3D,YDCV1%NS2D, &
        & YDCV1%STRUCT%NGRB)
      CALL ALLOCATE_SPEC(YLSP2,YDCV2%STRUCT%NFLEVL,YDCV2%STRUCT%NFLEVG, &
        & YDCV2%STRUCT%NUMP,YDCV2%STRUCT%MYMS,YDCV2%NSMAX,YDCV2%NMSMAX, &
        & YDCV2%STRUCT%NALLMS,YDCV2%STRUCT%NPTRMS,YDCV2%STRUCT%NUMLL, &
        & YDCV2%STRUCT%NPTRLL,YDCV2%STRUCT%NPSURF,YDCV2%NS3D,YDCV2%NS2D, &
        & YDCV1%STRUCT%NGRB)
      YLSP2=YDCV2%INITCV%DATA(:)
      YLSP1=YLSP2        ! Spectral_field type does change of resolution
      YDCV1%INITCV%DATA(:)=YLSP1
      CALL DEALLOCATE_SPEC(YLSP1)
      CALL DEALLOCATE_SPEC(YLSP2)
    ENDIF
  ENDIF

  IF (YDCV1%LENSCV) THEN
     IF (LL_SAME_ENS) THEN
        YDCV1%ENSCV%DATA(:) = YDCV2%ENSCV%DATA(:)
     ELSE
        IF (YDCV1%NENS /= YDCV2%NENS) CALL ABOR1("ENSEMBLE SIZE MISMATCH")
        WRITE(0,*)'CONTROL_VECTORS_OPER_MOD:ASSIGN_CV_CV::Spectral_field type does change of resolution'
        ALLOCATE(IGRB(2*YDCV1%NENS))
        DO II=1,2*YDCV1%NENS
           IGRB(II)=1000+II
        ENDDO
        CALL ALLOCATE_SPEC(YLSP1,YDCV1%STRUCT_ENS%NFLEVL,YDCV1%STRUCT_ENS%NFLEVG, &
             & YDCV1%STRUCT_ENS%NUMP,YDCV1%STRUCT_ENS%MYMS,YDCV1%NSMAX_ENS,YDCV1%NMSMAX_ENS, &
             & YDCV1%STRUCT_ENS%NALLMS,YDCV1%STRUCT_ENS%NPTRMS,YDCV1%STRUCT_ENS%NUMLL, &
             & YDCV1%STRUCT_ENS%NPTRLL, YDCV1%STRUCT_ENS%NPSURF,YDCV1%NENS,YDCV1%NENS,IGRB)
        CALL ALLOCATE_SPEC(YLSP2,YDCV2%STRUCT_ENS%NFLEVL,YDCV2%STRUCT_ENS%NFLEVG, &
             & YDCV2%STRUCT_ENS%NUMP,YDCV2%STRUCT_ENS%MYMS,YDCV2%NSMAX_ENS,YDCV2%NMSMAX_ENS, &
             & YDCV2%STRUCT_ENS%NALLMS,YDCV2%STRUCT_ENS%NPTRMS,YDCV2%STRUCT_ENS%NUMLL, &
             & YDCV2%STRUCT_ENS%NPTRLL,YDCV2%STRUCT_ENS%NPSURF,YDCV2%NENS,YDCV2%NENS,IGRB)
        YLSP2=YDCV2%ENSCV%DATA(:)
        YLSP1=YLSP2        ! Spectral_field type does change of resolution
        YDCV1%ENSCV%DATA(:)=YLSP1
        CALL DEALLOCATE_SPEC(YLSP1)
        CALL DEALLOCATE_SPEC(YLSP2)
        DEALLOCATE(IGRB)
     ENDIF
  ENDIF

  IF (YDCV1%NMODERR>0) THEN
    IF (LL_SAME_MODERR) THEN
      YDCV1%MODERR(:) = YDCV2%MODERR(:)
    ELSE
      CALL ALLOCATE_SPEC(YLSP1,YDCV1%STRUCT%NFLEVL,YDCV1%STRUCT%NFLEVG, &
       & YDCV1%STRUCT%NUMP,YDCV1%STRUCT%MYMS,YDCV1%NSERR,YDCV1%NSERR, &
       & YDCV1%STRUCT%NALLMS,YDCV1%STRUCT%NPTRMS,YDCV1%STRUCT%NUMLL, &
       & YDCV1%STRUCT%NPTRLL,YDCV1%STRUCT%NPSURF,YDCV1%NVE3D,YDCV1%NVE2D, &
       & YDCV1%STRUCT%NGRBE)
      CALL ALLOCATE_SPEC(YLSP2,YDCV2%STRUCT%NFLEVL,YDCV2%STRUCT%NFLEVG, &
       & YDCV2%STRUCT%NUMP,YDCV2%STRUCT%MYMS,YDCV2%NSERR,YDCV2%NSERR, &
       & YDCV2%STRUCT%NALLMS,YDCV2%STRUCT%NPTRMS,YDCV2%STRUCT%NUMLL, &
       & YDCV2%STRUCT%NPTRLL,YDCV2%STRUCT%NPSURF,YDCV2%NVE3D,YDCV2%NVE2D, &
       & YDCV1%STRUCT%NGRBE)
      IL1=YLSP1%NSPSIZEL
      IL2=YLSP2%NSPSIZEL
      DO JJ=1,YDCV1%NMODERR
        I1=(JJ-1)*IL1
        I2=(JJ-1)*IL2
        YLSP2=YDCV2%MODERR(I2+1:I2+IL2)
        YLSP1=YLSP2      ! Spectral_field type does change of resolution
        YDCV1%MODERR(I1+1:I1+IL1)=YLSP1
      ENDDO
      CALL DEALLOCATE_SPEC(YLSP1)
      CALL DEALLOCATE_SPEC(YLSP2)
    ENDIF
  ENDIF
  IF (YDCV1%LTOVSCV) THEN
    YDCV1%TOVSCV(:) = YDCV2%TOVSCV(:)
  ENDIF
  IF (YDCV1%LAM1D) THEN
    YDCV1%LAMCV(:) = YDCV2%LAMCV(:)
  ENDIF
  IF (YDCV1%NPARA>0) THEN
    YDCV1%PARAMS(:) = YDCV2%PARAMS(:)
  ENDIF
  IF (YDCV1%NPECV>0) THEN
    YDCV1%PECV(:) = YDCV2%PECV(:)
  ENDIF

ENDIF

IF (LHOOK) CALL DR_HOOK('CONTROL_VECTORS_OPER_MOD:ASSIGN_CV_CV',1,ZHOOK_HANDLE)
END SUBROUTINE ASSIGN_CV_CV

