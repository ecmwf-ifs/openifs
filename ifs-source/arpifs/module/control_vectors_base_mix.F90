SUBROUTINE INVERSE_CV(YDCV)
CLASS(CONTROL_VECTOR), INTENT(INOUT) :: YDCV

! divide_cv fails on zero, inverse sets output to zero.
REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
IF (LHOOK) CALL DR_HOOK('CONTROL_VECTORS_OPER_MOD:INVERSE_CV',0,ZHOOK_HANDLE)
CALL CHECK_CV(YDCV)
WHERE (YDCV%DATA /= 0.0_JPRB)
  YDCV%DATA = 1.0_JPRB/YDCV%DATA
ENDWHERE

IF (LHOOK) CALL DR_HOOK('CONTROL_VECTORS_OPER_MOD:INVERSE_CV',1,ZHOOK_HANDLE)
END SUBROUTINE INVERSE_CV

