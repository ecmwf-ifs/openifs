PROCEDURE, PASS(YDCV) :: INVERSE_CV
PROCEDURE, PASS(YDOUT):: INVERSE_CV_CV
PROCEDURE, PASS(YDCV1):: ASSIGN_CV_CV
PROCEDURE, PASS(YDCV) :: ASSIGN_CV_AR
PROCEDURE, PASS(YDCV) :: ASSIGN_AR_CV
PROCEDURE, PASS(YDCV) :: ASSIGN_SCALAR_CV
PROCEDURE, PASS(YDCV) :: DEALLOCATE_CV

GENERIC, PUBLIC :: ALLOCATE_CTLVEC   => ALLOCATE_CV, ALLOCATE_CV_CV
GENERIC, PUBLIC :: CHECK             => CHECK_CV, CHECK_CV_CV
GENERIC, PUBLIC :: OPERATOR(.EQV.)   => EQUIV_CV
GENERIC, PUBLIC :: OPERATOR(.NEQV.)  => NEQUIV_CV
GENERIC, PUBLIC :: ASSIGNMENT(=)     => ASSIGN_CV_CV, ASSIGN_SCALAR_CV, ASSIGN_AR_CV, ASSIGN_CV_AR
GENERIC, PUBLIC :: INVERSE           => INVERSE_CV, INVERSE_CV_CV
