SUBROUTINE COPY_FPRQPHY(Y_IN,Y_OUT)

 IMPLICIT NONE

 TYPE(TRQFP), INTENT(IN ) :: Y_IN
 TYPE(TRQFP), INTENT(OUT) :: Y_OUT

 INTEGER(KIND=JPIM) :: IDMP_SHAPE(2)

 REAL(KIND=JPHOOK) :: ZHOOK_HANDLE

 IF (LHOOK) CALL DR_HOOK('YOMFPDYN:COPY_FPRQPHY',0,ZHOOK_HANDLE)

 Y_OUT%NFIELDG=Y_IN%NFIELDG
 ALLOCATE(Y_OUT%ICOD(Y_OUT%NFIELDG))
 ALLOCATE(Y_OUT%IGRIB(Y_OUT%NFIELDG))
 ALLOCATE(Y_OUT%LLSURF(Y_OUT%NFIELDG))
 ALLOCATE(Y_OUT%CLNAME(Y_OUT%NFIELDG))
 ALLOCATE(Y_OUT%CLPREF(Y_OUT%NFIELDG))
 ALLOCATE(Y_OUT%IVEC(Y_OUT%NFIELDG))
 ALLOCATE(Y_OUT%IDOM(Y_OUT%NFIELDG))
 
 IDMP_SHAPE = SHAPE(Y_IN%IDMP)
 ALLOCATE(Y_OUT%IDMP(IDMP_SHAPE(1),Y_OUT%NFIELDG))

 Y_OUT%ICOD(:)   = Y_IN%ICOD(1:Y_OUT%NFIELDG)
 Y_OUT%CLPREF(:) = Y_IN%CLPREF(1:Y_OUT%NFIELDG)
 Y_OUT%CLNAME(:) = Y_IN%CLNAME(1:Y_OUT%NFIELDG)
 Y_OUT%IGRIB(:)  = Y_IN%IGRIB(1:Y_OUT%NFIELDG)
 Y_OUT%LLSURF(:) = Y_IN%LLSURF(1:Y_OUT%NFIELDG)
 Y_OUT%IVEC(:)   = Y_IN%IVEC(1:Y_OUT%NFIELDG)
 Y_OUT%IDOM(:)   = Y_IN%IDOM(1:Y_OUT%NFIELDG)
 Y_OUT%IDMP(:,:) = Y_IN%IDMP(1:IDMP_SHAPE(1),1:Y_OUT%NFIELDG)

 IF ( LALLOFP ) &
 CALL INQUIRE_FPRQPHY(Y_OUT,'FPHOLD:YDRQPHY',NULOUT)

 IF (LHOOK) CALL DR_HOOK('YOMFPDYN:COPY_FPRQPHY',1,ZHOOK_HANDLE)

END SUBROUTINE COPY_FPRQPHY

END MODULE YOMFPHOLD
