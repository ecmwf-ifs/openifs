SUBROUTINE COPY_TRQ3FP(TAG,Y_IN,Y_OUT)

 IMPLICIT NONE

 CHARACTER(LEN=*), INTENT(IN ) :: TAG
 TYPE(TRQ3FP),     INTENT(IN ) :: Y_IN
 TYPE(TRQ3FP),     INTENT(OUT) :: Y_OUT

 INTEGER(KIND=JPIM) :: KDOM

 REAL(KIND=JPHOOK) :: ZHOOK_HANDLE

 IF (LHOOK) CALL DR_HOOK('YOMFPDYN:COPY_TRQ3FP',0,ZHOOK_HANDLE)

 IF ( Y_IN%NPPFIELDG > 0 .AND. Y_IN%NPXLEV > 0 ) THEN
    KDOM=Y_IN%IDOM(1,1)
 ELSE
    KDOM=1
 ENDIF
 CALL ALLOCATE_TRQ3FP(Y_IN%NPPFIELDG,Y_IN%NPXLEV, KDOM, &
                      LALLOFP,NULOUT,Y_OUT)

 Y_OUT%NPPFIELDG = Y_IN%NPPFIELDG
 Y_OUT%NPXLEV    = Y_IN%NPXLEV   
 Y_OUT%NFIT      = Y_IN%NFIT     
 Y_OUT%NSPFIL    = Y_IN%NSPFIL     

 IF ( Y_IN%NPPFIELDG > 0 .AND. Y_IN%NPXLEV > 0 ) THEN
   Y_OUT%ZPXLEV  = Y_IN%ZPXLEV
   Y_OUT%NPPLEVG = Y_IN%NPPLEVG
   Y_OUT%ILEV    = Y_IN%ILEV
   Y_OUT%ICOD    = Y_IN%ICOD
   Y_OUT%IDOM    = Y_IN%IDOM
   Y_OUT%IDMP    = Y_IN%IDMP
 ENDIF

 IF (LHOOK) CALL DR_HOOK('YOMFPDYN:COPY_TRQ3FP',1,ZHOOK_HANDLE)

END SUBROUTINE COPY_TRQ3FP

!
