SUBROUTINE COPY_TRQ2FP(TAG,Y_IN,Y_OUT)

 IMPLICIT NONE

 CHARACTER(LEN=*), INTENT(IN ) :: TAG
 TYPE(TRQ2FP), INTENT(IN ) :: Y_IN
 TYPE(TRQ2FP), INTENT(OUT) :: Y_OUT

 INTEGER(KIND=JPIM) :: KDOM

 REAL(KIND=JPHOOK) :: ZHOOK_HANDLE

 IF (LHOOK) CALL DR_HOOK('YOMFPDYN:COPY_TRQ2FP',0,ZHOOK_HANDLE)

 Y_OUT%NPPFIELDG = Y_IN%NPPFIELDG
 IF ( Y_IN%NPPFIELDG > 0 ) THEN
    KDOM=Y_IN%IDOM(1)
 ELSE
    KDOM=1
 ENDIF

 CALL ALLOCATE_TRQ2FP(Y_IN%NPPFIELDG,KDOM,LALLOFP,NULOUT,Y_OUT)

 IF ( Y_IN%NPPFIELDG > 0 ) THEN
   Y_OUT%ICOD = Y_IN%ICOD
   Y_OUT%IDOM = Y_IN%IDOM
   Y_OUT%IDMP = Y_IN%IDMP
 ENDIF

 IF (LHOOK) CALL DR_HOOK('YOMFPDYN:COPY_TRQ2FP',1,ZHOOK_HANDLE)

END SUBROUTINE COPY_TRQ2FP

