IF (NTYPAER(5) /= 0) THEN
  ISSO4=NTYPAER(1)+NTYPAER(2)+NTYPAER(3)+NTYPAER(4)+1
  IF (LAERGTOP) THEN
    IF (LAERCHEM) THEN
      DO JK=1,KLEV
        DO JL=KIDIA,KFDIA
          IF (ISH2SO4_C > 0 .AND. JK < IKLEVTROP(JL)) THEN
            ZVPKEL=VAPOUR(PTP(JL,JK),PRSF1(JL,JK),PQP(JL,JK))
            ! strato : compute liquid H2SO4 production tendency (IFS-CBA) or
            ! SO2+OH-> SO4 tendency (IFS-CB05)
            ! If H2SO4 is a species (BASCOE on)
            ! H2SO4 partial pressure
            ZH2SO4_PP=ZH2SO4OK(JL,JK)*PRS1(JL,JK)*R/(ZMWH2SO4*287.05_JPRB)
            IF (ZVPKEL > 1.E-6 .AND. ZH2SO4_PP < ZVPKEL) THEN
              ZTSO4(JL,JK) = -0.03_JPRB*(PAEROP(JL,JK,ISSO4)+PTSPHY*ZTAEROK(JL,JK,ISSO4))/PTSPHY
              ZTH2SO4(JL,JK) = -1._JPRB*ZTSO4(JL,JK)*ZMWH2SO4/ZMWSO4
            ENDIF
            !       Calculate PH2SO4-H2O binary nucleation rate
            ZCORRH=MIN(MAX(0.1_JPRB,ZRHCL(JL,JK)),0.9_JPRB)
            ZACONS=5.E-12_JPRB
            ZBCONS=2._JPRB
            ZPAN=ZACONS*(((ZH2SO4OK(JL,JK))*ZRHO(JL,JK)*1.E14_JPRB)**ZBCONS) ! cm-3 s-1
            IF (ZPAN > 1.0E-8_JPRB .AND. ZH2SO4_PP >= ZVPKEL) THEN
              ZH2SO4NEW=ZH2SO4OK(JL,JK)*MAX(0.25_JPRB,EXP(-ZPAN*PTSPHY))
              ZTH2SO4(JL,JK) = ZTH2SO4(JL,JK)+(ZH2SO4NEW - ZH2SO4OK(JL,JK))/PTSPHY
              ZTH2SO4(JL,JK) = MAX(ZTH2SO4(JL,JK), -ZH2SO4OK(JL,JK)/PTSPHY)
              ZTSO4(JL,JK)=ZTSO4(JL,JK) - (ZH2SO4NEW - ZH2SO4OK(JL,JK))/PTSPHY*ZMWSO4/ZMWH2SO4
              ZTSO4(JL,JK) = MIN(ZTSO4(JL,JK), ZH2SO4OK(JL,JK)*ZMWSO4/ZMWH2SO4/PTSPHY)
            ENDIF
            PTENC(JL,JK,ISH2SO4_C)  =  PTENC(JL,JK,ISH2SO4_C)+ ZTH2SO4(JL,JK)
          ELSE
            ! Use conversion calculated in chemistry scheme in the troposphere or if BASCOE not used
            ZTSO4(JL,JK) = PCHEM2AER(JL,JK,1)
          ENDIF
          ZFSO4(JL) = ZFSO4(JL) + ZTSO4(JL,JK)*(ZDP(JL,JK)/RG)
          ZTAEROK(JL,JK,ISSO4)=ZTAEROK(JL,JK,ISSO4)+ZTSO4(JL,JK)
        ENDDO
      ENDDO
      ! SO4 Source
      DO JL=KIDIA,KFDIA
        ZAERSRC(JL,ISSO4)=ZAERSRC(JL,ISSO4)-ZFSO4(JL)
      ENDDO
    ELSE
      ISSO2=ISSO4+1
      DO JK=1,KLEV
        DO JL=KIDIA,KFDIA
!          ZSO2(JL,JK)=ZAEROK(JL,JK,ISSO2)
