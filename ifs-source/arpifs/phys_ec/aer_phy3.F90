    ENDDO
  ENDIF

   IF (LAEREQSAM4CLIM) THEN
 ! EQSAM4clim interface
    CALL AER_EQSAM4CLIM_IFS (YDEAERSNK,YDEAERATM,YDCOMPO,KIDIA , KFDIA, KLON,KLEV, IKLEVTROP,PRSF1,&
